"""Launch __PACKAGE__ standalone in Gazebo (gz sim -r -v4), no ROS robot."""

import os

from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, ExecuteProcess, SetEnvironmentVariable
from launch.substitutions import LaunchConfiguration


def generate_launch_description():
    world_file_name = '__NAME__.world'
    package_dir = get_package_share_directory('__PACKAGE__')
    world = LaunchConfiguration('world')

    model_path = os.path.join(package_dir, 'models')

    gazebo = ExecuteProcess(
        cmd=['gz', 'sim', '-r', '-v4', world], output='screen')

    return LaunchDescription([
        SetEnvironmentVariable('GZ_SIM_RESOURCE_PATH', model_path),
        DeclareLaunchArgument(
            'world',
            default_value=[os.path.join(package_dir, 'worlds', world_file_name), ''],
            description='SDF world file'),
        DeclareLaunchArgument(name='use_sim_time', default_value='true'),
        gazebo,
    ])


if __name__ == '__main__':
    generate_launch_description()
