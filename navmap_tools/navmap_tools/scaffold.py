"""
Build a whole `--package` colcon package tree for a navmap_gis_tool run.

Mirrors src/urjc-excavation-world's structure and file conventions exactly
(worlds/*.world, models/<name>/{model.sdf,model.config,meshes/}, maps/,
launch/*.launch.py, env-hooks/*.dsv.in) so the generated package plugs into
this workspace the same way that reference world package does -- see
easynav_gis_tool.md for why this structure was chosen. `--package` is the
exact ROS package name the user wants (e.g. "urjc_excavation_world"); the
shorter `name` used for the model directory and the world/mesh/map file
basenames is that package name with a trailing "_world" stripped, matching
how urjc-excavation-world itself is named ("urjc_excavation_world" package,
"urjc_excavation" model/mesh basename).

Scaffold files (package.xml, CMakeLists.txt, worlds/, models/, launch/,
env-hooks/, README.md) are always (re)written. `maps/` is left to the
caller (pcd_writer / the pointcloud_to_navmap tool): re-running with only
one of --gazebo/--navmap must not clobber files the other flag already
produced in a previous, separate invocation into the same --output-dir.
"""

from dataclasses import dataclass
from pathlib import Path


def _render(template: str, **kwargs) -> str:
    out = template
    for key, value in kwargs.items():
        out = out.replace(f'__{key.upper()}__', str(value))
    return out


@dataclass
class WorldPaths:
    """Resolved paths inside a generated `--package` package."""

    package_name: str
    name: str
    root: Path
    maps_dir: Path
    models_dir: Path
    model_dir: Path
    meshes_dir: Path
    worlds_dir: Path
    launch_dir: Path
    env_hooks_dir: Path

    @property
    def pcd_path(self) -> Path:
        """Path of the point cloud consumed/produced for --navmap."""
        return self.maps_dir / f'{self.name}.pcd'

    @property
    def navmap_path(self) -> Path:
        """Path of the generated .navmap file."""
        return self.maps_dir / f'{self.name}.navmap'

    @property
    def colors_csv_path(self) -> Path:
        """Path of the per-point RGB sidecar for the point cloud (see pcd_writer.py)."""
        return self.maps_dir / f'{self.name}_colors.csv'

    @property
    def world_path(self) -> Path:
        """Path of the generated .world SDF file."""
        return self.worlds_dir / f'{self.name}.world'

    @property
    def dae_path(self) -> Path:
        """Path of the generated visual mesh."""
        return self.meshes_dir / f'{self.name}.dae'

    @property
    def stl_path(self) -> Path:
        """Path of the generated collision mesh."""
        return self.meshes_dir / f'{self.name}.stl'

    @property
    def texture_path(self) -> Path:
        """Path of the generated diffuse texture."""
        return self.meshes_dir / f'{self.name}_texture.png'


def short_name_for(package_name: str) -> str:
    """
    Derive the model/mesh/world basename from a package name.

    Strips a trailing "_world" (e.g. "urjc_excavation_world" -> "urjc_excavation"),
    matching src/urjc-excavation-world's own naming; packages not following
    that convention are used as-is.
    """
    suffix = '_world'
    if package_name.endswith(suffix) and len(package_name) > len(suffix):
        return package_name[:-len(suffix)]
    return package_name


def world_paths(output_dir, package_name: str) -> WorldPaths:
    """Resolve every path inside the `<output_dir>` package for `package_name`."""
    name = short_name_for(package_name)
    root = Path(output_dir)
    models_dir = root / 'models'
    model_dir = models_dir / name
    return WorldPaths(
        package_name=package_name,
        name=name,
        root=root,
        maps_dir=root / 'maps',
        models_dir=models_dir,
        model_dir=model_dir,
        meshes_dir=model_dir / 'meshes',
        worlds_dir=root / 'worlds',
        launch_dir=root / 'launch',
        env_hooks_dir=root / 'env-hooks',
    )


