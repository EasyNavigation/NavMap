def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)


def scaffold_world_package(
    output_dir,
    package_name: str,
    center_lat: float,
    center_lon: float,
    size_m: float,
    elevation_amsl: float,
    imagery_desc: str,
    imagery_attribution: str = '',
) -> WorldPaths:
    """Create/update the `--package` package tree; returns its resolved paths."""
    if not package_name or not package_name.replace('_', '').isalnum():
        raise ValueError(
            f'package name must be a valid ROS package identifier: {package_name!r}')

    paths = world_paths(output_dir, package_name)
    paths.meshes_dir.mkdir(parents=True, exist_ok=True)
    paths.maps_dir.mkdir(parents=True, exist_ok=True)
    paths.worlds_dir.mkdir(parents=True, exist_ok=True)
    paths.launch_dir.mkdir(parents=True, exist_ok=True)
    paths.env_hooks_dir.mkdir(parents=True, exist_ok=True)

    kwargs = {
        'package': package_name, 'name': paths.name, 'lat': center_lat, 'lon': center_lon,
        'size': size_m, 'elevation': elevation_amsl, 'imagery_desc': imagery_desc,
        'imagery_attribution': imagery_attribution,
    }

    _write(paths.root / 'package.xml', _render(_PACKAGE_XML, **kwargs))
    _write(paths.root / 'CMakeLists.txt', _render(_CMAKELISTS, **kwargs))
    _write(paths.env_hooks_dir / f'{package_name}.dsv.in', _ENV_HOOK)
    _write(paths.model_dir / 'model.config', _render(_MODEL_CONFIG, **kwargs))
    _write(paths.model_dir / 'model.sdf', _render(_MODEL_SDF, **kwargs))
    _write(paths.world_path, _render(_WORLD_SDF, **kwargs))
    _write(paths.launch_dir / f'{paths.name}.launch.py', _render(_LAUNCH_PY, **kwargs))
    _write(paths.root / 'README.md', _render(_README, **kwargs))

    return paths
